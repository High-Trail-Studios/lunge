//! Lunge desktop app: a thin egui front end over `lunge-core`.

// A GUI app on Windows: without this, launching Lunge also opens a console.
#![cfg_attr(windows, windows_subsystem = "windows")]

mod add_session;
mod app;
mod create_dialog;
mod rename_dialog;
mod style;
mod theme;

use eframe::egui;

fn main() -> eframe::Result {
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title("Lunge")
            // Matches StartupWMClass in assets/lunge.desktop.
            .with_app_id("lunge")
            .with_inner_size([880.0, 600.0])
            .with_min_inner_size([600.0, 360.0])
            // The Dock icon on macOS (eframe sets it at runtime) and the
            // window icon on X11. Generated by assets/brand/make_icon.py.
            .with_icon(
                eframe::icon_data::from_png_bytes(include_bytes!("../assets/icon.png"))
                    .expect("bundled icon is a valid PNG"),
            ),
        // See the Windows dependencies in Cargo.toml for why.
        #[cfg(windows)]
        renderer: eframe::Renderer::Wgpu,
        ..Default::default()
    };
    eframe::run_native(
        "Lunge",
        options,
        Box::new(|cc| Ok(Box::new(app::LungeApp::new(cc)))),
    )
}
